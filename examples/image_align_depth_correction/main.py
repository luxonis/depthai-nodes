"""Verify ImageAlign -> axial correction -> PointCloud with deterministic replay.

Run with an installed depthai-nodes wheel and depthai==3.12.0. No camera, model,
recording, network input, or parcel algorithm is used. The same file runs on the
workstation or inside the accompanying OAK-4 standalone app.
"""

import argparse
import hashlib
import importlib.metadata
import json
import platform
from datetime import timedelta
from pathlib import Path

import depthai as dai
import numpy as np

import depthai_nodes
from depthai_nodes.node import ImageAlignDepthCorrection
from depthai_nodes.utils.axial_depth import AxialDepthPolicy


def installed_package_digest():
    """Identify actual installed package bytes, excluding generated bytecode."""
    distribution = importlib.metadata.distribution("depthai-nodes")
    digest = hashlib.sha256()
    for item in sorted(distribution.files or [], key=str):
        name = str(item)
        if name.startswith("depthai_nodes/") and not name.endswith(".pyc"):
            digest.update(name.encode() + b"\0")
            digest.update(
                hashlib.sha256(distribution.locate_file(item).read_bytes()).digest()
            )
    return digest.hexdigest()


def make_frame(size, intrinsics, pose, socket, sequence, *, depth=False):
    """Construct an associated frame with calibrated virtual-camera geometry."""
    width, height = size
    extrinsics = dai.Extrinsics(
        pose.tolist(), dai.CameraBoardSocket.CAM_A, dai.LengthUnit.MILLIMETER
    )
    extrinsics.toDeviceId = "axial-depth-synthetic/1"
    transformation = dai.ImgTransformation(
        width, height, intrinsics, dai.CameraModel.Perspective, [], extrinsics
    )
    frame = dai.ImgFrame()
    frame.setType(dai.ImgFrame.Type.RAW16 if depth else dai.ImgFrame.Type.RGB888i)
    frame.setWidth(width)
    frame.setHeight(height)
    frame.setStride(width * (2 if depth else 3))
    pixels = (
        np.full((height, width), 1000, dtype="<u2")
        if depth
        else np.full((height, width, 3), 127, dtype=np.uint8)
    )
    frame.setData(pixels.view(np.uint8).reshape(-1))
    frame.setTransformation(transformation)
    frame.setInstanceNum(int(socket))
    frame.setSequenceNum(sequence)
    frame.setTimestamp(timedelta(seconds=1))
    frame.setTimestampDevice(timedelta(seconds=1))
    return frame


def fixture():
    """Return different source/target grids and a rotated, translated source."""
    yaw, pitch = 0.12, -0.08
    ry = np.array(
        [[np.cos(yaw), 0, np.sin(yaw)], [0, 1, 0], [-np.sin(yaw), 0, np.cos(yaw)]]
    )
    rx = np.array(
        [
            [1, 0, 0],
            [0, np.cos(pitch), -np.sin(pitch)],
            [0, np.sin(pitch), np.cos(pitch)],
        ]
    )
    pose = np.eye(4)
    pose[:3, :3] = ry @ rx
    pose[:3, 3] = (20, 3, 10)
    source = make_frame(
        (96, 64),
        [[90, 0, 48], [0, 91, 32], [0, 0, 1]],
        pose,
        dai.CameraBoardSocket.CAM_B,
        17,
        depth=True,
    )
    target = make_frame(
        (80, 60),
        [[75, 0, 40], [0, 76, 30], [0, 0, 1]],
        np.eye(4),
        dai.CameraBoardSocket.CAM_A,
        71,
    )
    return source, target


def run(execution="host"):
    """Assert SDK source-Z behavior and corrected RGB-frame cloud geometry."""
    if dai.__version__ != "3.12.0":
        raise RuntimeError("This behavioral fixture requires depthai==3.12.0")
    native_device = execution == "oak4"
    source, target = fixture()
    with dai.Pipeline(createImplicitDevice=native_device) as pipeline:
        align = pipeline.create(dai.node.ImageAlign)
        align.setRunOnHost(not native_device)
        target_input = align.inputAlignTo.createInputQueue(maxSize=2, blocking=True)
        depth_input = align.input.createInputQueue(maxSize=2, blocking=True)
        correction = pipeline.create(ImageAlignDepthCorrection).build(
            alignedDepth=align.outputAligned,
            sourceDepth=align.passthroughInput,
            policy=AxialDepthPolicy.SOURCE_AXIAL_REQUIRES_CORRECTION,
        )
        cloud = pipeline.create(dai.node.PointCloud)
        cloud.setRunOnHost(not native_device)
        cloud.sync.setRunOnHost(not native_device)
        cloud.initialConfig.setLengthUnit(dai.LengthUnit.MILLIMETER)
        cloud.initialConfig.setOrganized(True)
        correction.out.link(cloud.inputDepth)
        raw_output = align.outputAligned.createOutputQueue(maxSize=2, blocking=True)
        corrected_output = correction.result.createOutputQueue(maxSize=2, blocking=True)
        cloud_output = cloud.outputPointCloud.createOutputQueue(
            maxSize=2, blocking=True
        )
        pipeline.start()
        target_input.send(target)
        depth_input.send(source)
        wait = timedelta(seconds=30)
        aligned = raw_output.get(wait)
        result = corrected_output.get(wait)
        point_data = cloud_output.get(wait)
        if aligned is None or result is None or point_data is None:
            raise RuntimeError("The correction pipeline did not complete its fixture")
        raw = np.asarray(aligned.getFrame())
        corrected = np.asarray(result.frame.getFrame())
        valid = (raw > 0) & (raw < 65535)
        assert int(valid.sum()) > 1000
        np.testing.assert_array_equal(raw[valid], 1000)
        assert np.ptp(corrected[valid]) > 50
        source_pose = np.asarray(
            source.getTransformation()
            .getExtrinsics()
            .getTransformationMatrix(unit=dai.LengthUnit.MILLIMETER)
        )
        target_pose = np.asarray(
            aligned.getTransformation()
            .getExtrinsics()
            .getTransformationMatrix(unit=dai.LengthUnit.MILLIMETER)
        )
        height, width = corrected.shape
        v, u = np.indices((height, width))
        pixels = np.stack((u, v, np.ones_like(u)), axis=-1)
        k = np.asarray(aligned.getTransformation().getIntrinsicMatrix())
        rays = np.linalg.solve(k, pixels.reshape(-1, 3).T).T
        points = np.asarray(point_data.getPoints()).reshape(height, width, 3)
        expected_cloud = rays.reshape(height, width, 3) * corrected[:, :, None]
        np.testing.assert_allclose(
            points[valid], expected_cloud[valid], atol=0.01, rtol=0
        )
        reference_points = points[valid] @ target_pose[:3, :3].T + target_pose[:3, 3]
        source_points = np.linalg.solve(
            source_pose[:3, :3], (reference_points - source_pose[:3, 3]).T
        ).T
        residual = float(np.max(np.abs(source_points[:, 2] - 1000)))
        assert residual < 0.6, residual
        uncorrected = rays.reshape(height, width, 3)[valid] * raw[valid, None]
        source_uncorrected = np.linalg.solve(
            source_pose[:3, :3], (uncorrected - source_pose[:3, 3]).T
        ).T
        raw_residual = float(np.max(np.abs(source_uncorrected[:, 2] - 1000)))
        assert raw_residual > 50
        for frame in (aligned, result.frame, point_data):
            assert frame.getSequenceNum() == source.getSequenceNum()
            assert frame.getTimestampDevice() == source.getTimestampDevice()
        np.testing.assert_array_equal(source.getFrame(), 1000)
        provenance = result.provenance.to_dict()
        report = dict(
            schema="depthai-nodes-axial-verification/1",
            sdk_version=dai.__version__,
            package_version=importlib.metadata.version("depthai-nodes"),
            package_path=str(Path(depthai_nodes.__file__).resolve()),
            installed_package_sha256=installed_package_digest(),
            architecture=platform.machine(),
            execution=execution,
            placement=dict(
                image_align="device" if native_device else "host_cpu",
                correction="application_cpu",
                point_cloud="device" if native_device else "host_cpu",
            ),
            valid_pixels=int(valid.sum()),
            maximum_corrected_source_plane_residual_mm=residual,
            maximum_uncorrected_source_plane_residual_mm=raw_residual,
            corrected_depth_sha256=hashlib.sha256(corrected.tobytes()).hexdigest(),
            source_z_retained_by_image_align=True,
            correction=provenance,
        )
        pipeline.stop()
        return report


def main():
    """Print a machine-readable verification record and optionally save it."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execution", choices=("host", "oak4"), default="host")
    parser.add_argument("--report", type=Path)
    arguments = parser.parse_args()
    report = run(arguments.execution)
    payload = json.dumps(report, indent=2, sort_keys=True)
    if arguments.report:
        arguments.report.parent.mkdir(parents=True, exist_ok=True)
        arguments.report.write_text(payload + "\n")
    print(payload, flush=True)


if __name__ == "__main__":
    main()
